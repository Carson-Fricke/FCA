//! engine (`hashlib.sha256`), and the workspace deliberately keeps the staged
//! Rust crates free of third-party dependencies until the migration flips.
//! This module implements FIPS 180-4 SHA-256 over the standard padding rules
//! and is validated against the published test vectors in the unit tests.

